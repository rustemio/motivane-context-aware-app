/*
  Словарь приложения.

  Заметка здесь не имеет срока. Вместо даты у неё список условий — что должно
  совпасть в мире, чтобы за неё стоило взяться. «Позвонить бабушке» ждёт
  вечера буднего дня, «сходить за плёнкой» — ясного дня и того, что я в
  городе, «дописать сценарий» — дождя.
*/

/** Что видно на небе. Названия свои: у погодных служб коды разные, сводим к четырём. */
export type Sky = 'clear' | 'cloud' | 'rain' | 'snow';

/**
 * Одно условие заметки.
 *
 * Условия складываются по «и»: заметка созрела, когда совпали все. «Или» тут
 * нарочно нет — оно читается как «неважно когда», а это ровно то, от чего
 * приложение уходит.
 */
export type Condition =
  | { kind: 'sky'; is: Sky }
  /** Температура воздуха, °C. Одна граница или обе. */
  | { kind: 'temp'; min?: number; max?: number }
  /** Светло или темно на улице: считается по восходу и закату, а не по часам. */
  | { kind: 'light'; is: 'day' | 'night' }
  /** Окно часов по местному времени, 0—23. from > to читается через полночь: 22→6. */
  | { kind: 'hours'; from: number; to: number }
  /** Дни недели, 0 — воскресенье, как у Date.getDay(). */
  | { kind: 'weekday'; days: readonly number[] }
  /** Радиус вокруг точки, метры. label — как это место называет владелец. */
  | { kind: 'place'; lat: number; lon: number; within: number; label: string };

export type Note = {
  id: string;
  text: string;
  /** Когда записана, мс. */
  created: number;
  needs: Condition[];
  /** Когда вычеркнута, мс. Вычеркнутая заметка из облака уходит. */
  doneAt?: number;
};

/**
 * Снимок мира на один момент. Поля необязательные не для красоты: погоды может
 * не быть из-за сети, места — из-за отказа в доступе. Пустое поле и ноль — это
 * разные вещи, и движок обязан их различать.
 */
export type World = {
  /** Момент снимка, мс. */
  at: number;
  /** Местный час, 0—23. Считается тут, а не в движке: часовой пояс знает устройство. */
  hour: number;
  /** День недели, 0—6. */
  weekday: number;
  sky?: Sky;
  tempC?: number;
  /** Восход и закат этого дня, мс. Нет — про свет ответить нечем. */
  sunrise?: number;
  sunset?: number;
  here?: { lat: number; lon: number };
};

/**
 * Ответ на одно условие.
 *
 * Третье значение — главное решение всего движка. Без него отказ в доступе к
 * геопозиции превратился бы либо в «условие выполнено» (заметка врёт, что
 * пора), либо в «не выполнено» (заметка молчит навсегда, и непонятно почему).
 * `unknown` говорит правду: проверить нечем.
 */
export type Verdict = 'yes' | 'no' | 'unknown';

/** Что стало с заметкой после сверки с миром. */
export type State =
  /** Все условия сошлись. */
  | 'ripe'
  /** Хотя бы одно условие не выполнено. */
  | 'waiting'
  /** Никто не сказал «нет», но чего-то о мире мы не знаем. */
  | 'unsure';
